CREATE TABLE IF NOT EXISTS players (
  pid TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  lang TEXT,
  s1 INTEGER NOT NULL DEFAULT 0,
  s2 INTEGER NOT NULL DEFAULT 0,
  s3 INTEGER NOT NULL DEFAULT 0,
  s4 INTEGER NOT NULL DEFAULT 0,
  s5 INTEGER NOT NULL DEFAULT 0,
  total INTEGER NOT NULL DEFAULT 0,
  updated INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_total ON players(total DESC);
CREATE INDEX IF NOT EXISTS idx_s1 ON players(s1 DESC);
CREATE INDEX IF NOT EXISTS idx_s2 ON players(s2 DESC);
CREATE INDEX IF NOT EXISTS idx_s3 ON players(s3 DESC);
CREATE INDEX IF NOT EXISTS idx_s4 ON players(s4 DESC);
CREATE INDEX IF NOT EXISTS idx_s5 ON players(s5 DESC);
